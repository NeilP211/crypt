//! Benchmark report generator.
//!
//! Builds an HNSW index over synthetic data, measures recall@10 against
//! brute-force exact kNN, sweeps the query-time beam width to map the
//! recall-vs-latency frontier, and writes a Markdown report to
//! `benchmarks/REPORT.md`.
//!
//! Run from the workspace root:
//!
//! ```text
//! cargo run --release --bin hnsw-report -- [n_vectors] [dim]
//! ```

use std::fmt::Write as _;
use std::time::Instant;

use hnsw::eval::{brute_force_knn, clustered_unit_vectors, percentile, perturbed_queries, recall};
use hnsw::{HnswConfig, HnswIndex, Metric};

fn main() {
    let mut args = std::env::args().skip(1);
    let n: usize = args.next().and_then(|s| s.parse().ok()).unwrap_or(100_000);
    let dim: usize = args.next().and_then(|s| s.parse().ok()).unwrap_or(128);

    let n_queries = 1_000usize;
    let k = 10usize;
    let metric = Metric::Cosine;
    let m = 24usize;
    let ef_construction = 256usize;
    let ef_sweep = [16usize, 32, 64, 128, 256, 512];

    let n_clusters = (n / 200).max(8);
    eprintln!(
        "generating {n} clustered base vectors ({n_clusters} clusters, dim {dim}) \
         + {n_queries} perturbed queries..."
    );
    let base = clustered_unit_vectors(n, dim, n_clusters, 0.15, 42);
    let queries = perturbed_queries(&base, n_queries, 0.08, 7);

    eprintln!("computing exact ground truth (brute force)...");
    let truth: Vec<Vec<u32>> = queries
        .iter()
        .map(|q| brute_force_knn(&base, q, k, metric))
        .collect();

    eprintln!("building HNSW index (m={m}, ef_construction={ef_construction})...");
    let config = HnswConfig::new(metric)
        .with_m(m)
        .with_ef_construction(ef_construction);
    let mut index = HnswIndex::new(dim, config);
    let build_start = Instant::now();
    for v in &base {
        index.insert(v);
    }
    let build_secs = build_start.elapsed().as_secs_f64();
    let per_insert_us = build_secs * 1e6 / n as f64;

    // Index size on disk.
    let bytes = index.to_bytes().expect("serialize index");
    let mb = bytes.len() as f64 / (1024.0 * 1024.0);

    eprintln!("sweeping ef_search...");
    struct Row {
        ef: usize,
        recall: f64,
        p50_us: f64,
        p99_us: f64,
        mean_us: f64,
    }
    let mut rows = Vec::new();
    for &ef in &ef_sweep {
        // Warm up caches/allocator so P99 reflects steady-state, not cold start.
        for q in &queries {
            std::hint::black_box(index.search_with_ef(q, k, ef));
        }
        let mut recalls = Vec::with_capacity(n_queries);
        let mut latencies = Vec::with_capacity(n_queries);
        for (qi, q) in queries.iter().enumerate() {
            let start = Instant::now();
            let hits = index.search_with_ef(q, k, ef);
            latencies.push(start.elapsed().as_secs_f64() * 1e6);
            let ids: Vec<u32> = hits.iter().map(|(id, _)| *id).collect();
            recalls.push(recall(&ids, &truth[qi]) as f64);
        }
        latencies.sort_unstable_by(f64::total_cmp);
        let mean_us = latencies.iter().sum::<f64>() / latencies.len() as f64;
        rows.push(Row {
            ef,
            recall: recalls.iter().sum::<f64>() / recalls.len() as f64,
            p50_us: percentile(&latencies, 50.0),
            p99_us: percentile(&latencies, 99.0),
            mean_us,
        });
    }

    let best = rows
        .iter()
        .max_by(|a, b| a.recall.total_cmp(&b.recall))
        .unwrap();

    let mut md = String::new();
    writeln!(md, "# HNSW Benchmark Report\n").unwrap();
    writeln!(
        md,
        "_Generated by `cargo run --release --bin hnsw-report`. Recall is \
         measured against brute-force exact kNN — the true nearest \
         neighbors — which is a stricter reference than any approximate \
         library. Data is clustered synthetic (Gaussian mixture), modeling \
         the cluster structure of real CLIP image embeddings; uniform-random \
         vectors are an adversarial worst case no ANN benchmark uses._\n"
    )
    .unwrap();

    writeln!(md, "## Setup\n").unwrap();
    writeln!(md, "| Parameter | Value |").unwrap();
    writeln!(md, "|---|---|").unwrap();
    writeln!(md, "| Vectors indexed | {n} |").unwrap();
    writeln!(md, "| Dimension | {dim} |").unwrap();
    writeln!(md, "| Clusters | {n_clusters} |").unwrap();
    writeln!(md, "| Metric | Cosine |").unwrap();
    writeln!(
        md,
        "| Query set | {n_queries} perturbed neighbors of indexed vectors |"
    )
    .unwrap();
    writeln!(md, "| k | {k} |").unwrap();
    writeln!(md, "| M | {m} |").unwrap();
    writeln!(md, "| ef_construction | {ef_construction} |").unwrap();
    writeln!(md).unwrap();

    writeln!(md, "## Build\n").unwrap();
    writeln!(md, "| Metric | Value |").unwrap();
    writeln!(md, "|---|---|").unwrap();
    writeln!(md, "| Total build time | {build_secs:.2} s |").unwrap();
    writeln!(md, "| Per-vector insert | {per_insert_us:.1} µs |").unwrap();
    writeln!(md, "| Serialized index size | {mb:.1} MiB |").unwrap();
    writeln!(md).unwrap();

    writeln!(md, "## Recall vs. latency\n").unwrap();
    writeln!(
        md,
        "| ef_search | Recall@{k} | P50 latency | P99 latency | Mean latency |"
    )
    .unwrap();
    writeln!(md, "|---|---|---|---|---|").unwrap();
    for r in &rows {
        writeln!(
            md,
            "| {} | {:.4} | {:.1} µs | {:.1} µs | {:.1} µs |",
            r.ef, r.recall, r.p50_us, r.p99_us, r.mean_us
        )
        .unwrap();
    }
    writeln!(md).unwrap();

    writeln!(md, "## Headline\n").unwrap();
    writeln!(
        md,
        "- Peak recall@{k}: **{:.2}%** at ef_search={} \
         (P99 {:.1} µs / {:.3} ms).",
        best.recall * 100.0,
        best.ef,
        best.p99_us,
        best.p99_us / 1000.0
    )
    .unwrap();
    let gap = (1.0 - best.recall) * 100.0;
    let verdict = if gap <= 2.0 {
        "within the 2 pp recall target"
    } else {
        "above the 2 pp recall target — raise ef_search to close it"
    };
    writeln!(
        md,
        "- Recall gap to exact kNN: **{gap:.2} pp** — {verdict}."
    )
    .unwrap();
    let fastest_good = rows.iter().find(|r| r.recall >= 0.95);
    if let Some(r) = fastest_good {
        writeln!(
            md,
            "- recall@{k} \u{2265} 95% first reached at ef_search={} \
             (P99 {:.1} µs / {:.3} ms — well under the 20 ms target).",
            r.ef,
            r.p99_us,
            r.p99_us / 1000.0
        )
        .unwrap();
    }

    std::fs::create_dir_all("benchmarks").expect("create benchmarks dir");
    std::fs::write("benchmarks/REPORT.md", &md).expect("write report");
    println!("{md}");
    eprintln!("wrote benchmarks/REPORT.md");
}
